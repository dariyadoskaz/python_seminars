"""
Задание 1: Видеокарты
В базе магазина электроники есть список видеокарт компании NVIDIA разных
поколений. Вместо полных названий хранятся только числа, которые обозначают
модель и поколение видеокарты. Недавно компания выпустила новую линейку
видеокарт. Самые старшие поколения разобрали за пару дней.
Напишите программу, которая удаляет наибольшие элементы из списка видеокарт.
Пример:
Количество видеокарт: 5
Видеокарта 1: 3070
Видеокарта 2: 2060
Видеокарта 3: 3090
Видеокарта 4: 3070
Видеокарта 5: 3090
Старый список видеокарт: [ 3070 2060 3090 3070 3090 ]
Новый список видеокарт: [ 3070 2060 3070 ]

"""

n = int(input("Количество видеокарт: "))

video_cards = []
for i in range(n):
    card = int(input(f"Видеокарта {i + 1}: "))
    video_cards.append(card)

max_card = max(video_cards)
new_video_cards = [card for card in video_cards if card != max_card]

print("Старый список видеокарт:", video_cards)
print("Новый список видеокарт:", new_video_cards)


"""
Задача 2. Кино
Илья зашёл на любительский киносайт, на котором пользователи оставляют рецензии на фильмы. Их список:
films = [‘Крепкий орешек’, ‘Назад в будущее’, ‘Таксист’, ‘Леон’, ‘Богемская рапсодия’, ‘Город грехов’, ‘Мементо’, ‘Отступники’, ‘Деревня’]
Илья на сайте в первый раз. Он хочет зарегистрироваться и сразу добавить часть фильмов в список любимых, чтобы позже прочитать рецензии на них.
Напишите программу, в которой пользователь вводит фильм. Если кинокартина есть в перечне, то добавляется в список любимых. 
Если её нет, то выводится ошибка. В конце выведите весь список любимых фильмов.
Пример:
Сколько фильмов хотите добавить? 3
Введите название фильма: Леон
Введите название фильма: Безумный Макс

"""

films = ['Крепкий орешек', 'Назад в будущее', 'Таксист', 'Леон', 'Богемская рапсодия', 'Город грехов', 'Мементо', 'Отступники', 'Деревня']

favorite_films = []

n = int(input("Сколько фильмов хотите добавить? "))

for i in range(n):
    film = input("Введите название фильма: ")
    if film in films:
        favorite_films.append(film)
    else:
        print(f"Ошибка: Фильм '{film}' не найден в списке.")

print("Ваш список любимых фильмов:", favorite_films)


"""
Задача 4. Товары
В базе данных магазина вся необходимая информация по товарам делится на два словаря: 
первый отвечает за коды товаров, второй — за списки количества разнообразных товаров на складе:

goods = {
'Лампа': '12345',
'Стол': '23456',
'Диван': '34567',
'Стул': '45678',
}

store = {

'12345': [
{'quantity': 27, 'price': 42},
],

'23456': [
{'quantity': 22, 'price': 510},
{'quantity': 32, 'price': 520},
],

'34567': [
{'quantity': 2, 'price': 1200},
{'quantity': 1, 'price': 1150}
{'quantity': 12, 'price': 95},
{'quantity': 43, 'price': 97},
],
}
Каждая запись второго словаря отображает, сколько и по какой цене закупалось товаров. Цена указана за одну штуку.
Напишите программу, которая рассчитывает общую стоимость позиций для каждого товара на складе и выводит эту информацию на экран.
Результат работы программы:
Лампа — 27 штук, стоимость 1134 рубля.
Стол — 54 штуки, стоимость 27 860 рублей.
Диван — 3 штуки, стоимость 3550 рублей.
Стул — 105 штук, стоимость 10 311 рублей.
"""


goods = {
    'Лампа': '12345',
    'Стол': '23456',
    'Диван': '34567',
    'Стул': '45678',
}

store = {
    '12345': [
        {'quantity': 27, 'price': 42},
    ],
    '23456': [
        {'quantity': 22, 'price': 510},
        {'quantity': 32, 'price': 520},
    ],
    '34567': [
        {'quantity': 2, 'price': 1200},
        {'quantity': 1, 'price': 1150},
        {'quantity': 12, 'price': 95},
        {'quantity': 43, 'price': 97},
    ],
    '45678': [
        {'quantity': 57, 'price': 82},
        {'quantity': 48, 'price': 85},
    ],
}

for item_name, item_code in goods.items():
    total_quantity = 0
    total_cost = 0
    for item in store[item_code]:
        total_quantity += item['quantity']
        total_cost += item['quantity'] * item['price']

    print(f"{item_name} — {total_quantity} штук, стоимость {total_cost} рублей.")
